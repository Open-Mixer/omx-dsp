/*
 * rta-delta-golden — writes vectors/rta-delta.json: the difference of two taps (analysis/omx_rta_bands.h
 * omx_rta_band_delta) over pairs of band readings made by omx_rta_bands from the scenarios of
 * test/kernels/fixtures/rta_bands_scenarios.h, at 48 and 96 kHz and band counts 1, 2 (the first pair), 64 and 160.
 * Each case carries its inputs (preDb, postDb, null for silence) and its answer (diff, null where either tap is
 * silent; wedges as [band, boost 1/0, strength]), every number "%.17g". A last case, "edges", is made by hand: a
 * difference of exactly the deadband and of 0.99 of it, one past the EQ's limit, a silent band and a +3/-5 pair,
 * which no scenario lands on, so a twin that moves an edge disagrees with the file. Run by `make rta-delta-golden`; the suite's rta_delta arm and the
 * TypeScript twin's test read it back. One case per line.
 */
#include <stdio.h>

#include "../test/kernels/fixtures/rta_bands_scenarios.h"

static struct rb_case c;
static struct omx_rta_band pre[RB_MAX_BANDS], post[RB_MAX_BANDS];
static double diff[RB_MAX_BANDS];
static struct omx_rta_wedge wedges[RB_MAX_BANDS];

static void num(double x) {
  if (isinf(x) || isnan(x)) printf("null");
  else printf("%.17g", x);
}

static void levels(const char *key, const struct omx_rta_band *b, uint32_t n) {
  printf(", \"%s\": [", key);
  for (uint32_t i = 0; i < n; i++) printf("%s", i ? ", " : ""), num(b[i].db);
  printf("]");
}

/* A reading of `kind`, or `kind` shaped by a gentle EQ-like ripple of 0.8 dB around the deadband (shape 1). */
static void reading(int kind, int shape, float rate, uint32_t n, struct omx_rta_band *out) {
  rb_build((enum rb_kind)kind, rate, &c);
  omx_rta_bands(&c.h, c.has_low ? &c.l : NULL, n, out);
  if (shape)
    for (uint32_t i = 0; i < n; i++) out[i].db += 0.8 * sin(0.37 * (double)i);
}

/* PRE, POST: a processor that changes nothing, one that ripples, two different signals both ways, a silent POST, a
 * silent PRE. */
static const int PAIRS[][4] = {
    {RB_SLOPE, 0, RB_SLOPE, 0}, {RB_SLOPE, 0, RB_SLOPE, 1}, {RB_TONES, 0, RB_TONES, 1},
    {RB_SLOPE, 0, RB_TONES, 0}, {RB_TONES, 0, RB_SLOPE, 0}, {RB_TONES, 0, RB_SILENCE, 0},
    {RB_SILENCE, 0, RB_TONES, 0},
};
#define PAIRS_COUNT (sizeof PAIRS / sizeof PAIRS[0])
static const uint32_t COUNTS[] = {1u, 2u, 64u, 160u};
#define COUNTS_COUNT (sizeof COUNTS / sizeof COUNTS[0])

int main(void) {
  printf("{\n");
  printf("  \"doc\": \"GENERATED by tools/rta-delta-golden.c (make rta-delta-golden) - do not edit. The difference of two "
         "taps (omx_rta_band_delta of omx_rta_bands.h) over pairs of band readings of the scenarios of "
         "test/kernels/fixtures/rta_bands_scenarios.h at 48 and 96 kHz and band counts 1, 2, 64 and 160: preDb and postDb "
         "the inputs (null silence), diff POST - PRE (null where either is silent), wedges [band, boost, strength]. One "
         "case per line.\",\n");
  printf("  \"law\": {\"deadbandDb\": %.17g, \"fullScaleDb\": %.17g},\n", OMX_RTA_DELTA_DEADBAND_DB_DOUBLE,
         (double)OMX_EQ_GAIN_RANGE_MAX);
  printf("  \"cases\": [\n");
  int first = 1;
  for (uint32_t ri = 0; ri < RB_FILE_RATES_COUNT; ri++)
    for (uint32_t p = 0; p < PAIRS_COUNT; p++)
      for (uint32_t ni = 0; ni < COUNTS_COUNT; ni++) {
        const uint32_t n = COUNTS[ni];
        const float rate = RB_FILE_RATES[ri];
        reading(PAIRS[p][0], PAIRS[p][1], rate, n, pre);
        reading(PAIRS[p][2], PAIRS[p][3], rate, n, post);
        const uint32_t k = omx_rta_band_delta(pre, post, n, diff, wedges);
        printf("%s    {\"case\": \"%s%s>%s%s\", \"rate\": %.17g, \"n\": %u", first ? "" : ",\n",
               RB_KIND_NAMES[PAIRS[p][0]], PAIRS[p][1] ? "~" : "", RB_KIND_NAMES[PAIRS[p][2]], PAIRS[p][3] ? "~" : "",
               (double)rate, n);
        first = 0;
        levels("preDb", pre, n), levels("postDb", post, n);
        printf(", \"diff\": [");
        for (uint32_t i = 0; i < n; i++) printf("%s", i ? ", " : ""), num(diff[i]);
        printf("], \"wedges\": [");
        for (uint32_t j = 0; j < k; j++)
          printf("%s[%u, %d, %.17g]", j ? ", " : "", wedges[j].band, wedges[j].boost, wedges[j].strength);
        printf("]}");
      }
  /* The edges, which no scenario lands on: PRE at -1 dB in 12 bands and POST - PRE of 0, exactly the deadband, 0, 0,
   * 0.99 of it, 0, 0, 30 (past the EQ's limit), a silent POST band, +3, -5, 0. */
  const double dead = OMX_RTA_DELTA_DEADBAND_DB_DOUBLE;
  const double edge[12] = {0, dead, 0, 0, dead * 0.99, 0, 0, 30, -INFINITY, 3, -5, 0};
  for (uint32_t i = 0; i < 12u; i++) {
    pre[i] = (struct omx_rta_band){0.0, -1.0, -1.0};
    post[i] = (struct omx_rta_band){0.0, -1.0 + edge[i], -1.0 + edge[i]};
  }
  const uint32_t k = omx_rta_band_delta(pre, post, 12u, diff, wedges);
  printf(",\n    {\"case\": \"edges\", \"rate\": 0, \"n\": 12");
  levels("preDb", pre, 12u), levels("postDb", post, 12u);
  printf(", \"diff\": [");
  for (uint32_t i = 0; i < 12u; i++) printf("%s", i ? ", " : ""), num(diff[i]);
  printf("], \"wedges\": [");
  for (uint32_t j = 0; j < k; j++)
    printf("%s[%u, %d, %.17g]", j ? ", " : "", wedges[j].band, wedges[j].boost, wedges[j].strength);
  printf("]}");
  printf("\n  ]\n}\n");
  return 0;
}

/*
 * rta-bands-golden — writes vectors/rta-bands.json: the band reduction (analysis/omx_rta_bands.h) over the scenarios of
 * test/kernels/fixtures/rta_bands_scenarios.h, every number "%.17g" and silence as null, so no value is rounded on the
 * way. Run by `make rta-bands-golden`; the suite's rta_bands arm and the TypeScript twin's test (ts/test/rta-bands.test.mjs)
 * read the file back. One case per line. A change of the reduction re-runs it in the commit that makes the change, and
 * the diff is the review.
 */
#include <stdio.h>

#include "../test/kernels/fixtures/rta_bands_scenarios.h"

static struct rb_case c;
static struct omx_rta_band out[RB_MAX_BANDS];

static void num(double x) {
  if (isinf(x) && x < 0) printf("null");
  else printf("%.17g", x);
}

static void arr(const char *key, uint32_t n, int field) {
  printf(", \"%s\": [", key);
  for (uint32_t i = 0; i < n; i++) {
    if (i) printf(", ");
    num(field == 0 ? out[i].hz : field == 1 ? out[i].db : out[i].peak_db);
  }
  printf("]");
}

int main(void) {
  printf("{\n");
  printf("  \"doc\": \"GENERATED by tools/rta-bands-golden.c (make rta-bands-golden) - do not edit. The band reduction of "
         "omx_rta_bands.h over the scenarios of test/kernels/fixtures/rta_bands_scenarios.h at 48 and 96 kHz and band counts "
         "1, 64 and 640: hz the geometric centres, db the RMS across each band and peak its loudest bin, in dBFS, null for "
         "silence. The tiers scenario carries the low zoom's tier. One case per line.\",\n");
  printf("  \"law\": {\"fMin\": %.17g, \"fMaxCap\": %.17g, \"crossoverHz\": %.17g, \"gateDb\": %.17g},\n",
         (double)OMX_RTA_BAND_F_MIN, (double)OMX_RTA_BAND_F_MAX_CAP, (double)OMX_RTA_TIER_CROSSOVER_HZ,
         (double)OMX_RTA_BAND_GATE_DB);
  printf("  \"cases\": [\n");
  int first = 1;
  for (uint32_t ri = 0; ri < RB_FILE_RATES_COUNT; ri++)
    for (int k = 0; k < RB_KINDS; k++)
      for (uint32_t ni = 0; ni < RB_BAND_COUNTS_COUNT; ni++) {
        rb_build((enum rb_kind)k, RB_FILE_RATES[ri], &c);
        const uint32_t n = omx_rta_bands(&c.h, c.has_low ? &c.l : NULL, RB_BAND_COUNTS[ni], out);
        printf("%s    {\"kind\": \"%s\", \"rate\": %.17g, \"n\": %u, \"low\": %s", first ? "" : ",\n", RB_KIND_NAMES[k],
               (double)RB_FILE_RATES[ri], n, c.has_low ? "true" : "false");
        first = 0;
        arr("hz", n, 0), arr("db", n, 1), arr("peak", n, 2);
        printf("}");
      }
  printf("\n  ]\n}\n");
  return 0;
}
